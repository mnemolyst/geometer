        break;
      } else {
        $new_path[] = $valid_points[rand(0, count($valid_points)-1)];
      }
    }

    return $new_path;
  }

  $points[] = array(
    '0',
    '0',
    'connected' => array()
  );

  foreach (array_keys($lines) as $i) {
    $points_on_line = array();
    foreach (array_keys($points) as $j) {
      if (point_on_line($j, $i)) {
        $points_on_line[] = $j;
      }
    }
    foreach ($points_on_line as $j => $p) {
      $this_connected = $points_on_line;
      unset($this_connected[$j]);
      $points[$p]['connected'] += $this_connected;
    }
  }

  $path = array();
  foreach($points as $point) {
    if ($point[0] == '0' && $point[1] == '0') {
      $path = $point['connected'];
    }
  }

  while (FALSE) {
    //print_r($path);
    //print "<br>";
    $cur_score = path_score($path);
    $max_score = null;
    $valid_points = valid_next_points($path);
    foreach ($valid_points as $p) {
      $trial_path = $path;
      $trial_path[] = $p;

      //approximate the max score that could result from adding $point to $path
      for ($i=0; $i<5; $i++) {
        $rand_path = rand_end($trial_path);
        $this_score = path_score($rand_path);
        if ($this_score > $max_score || $max_score == null) {
          $max_score = $this_score;
          $max_point = $p;
        }
      }
    }

    if ($max_score != null && $max_score > $cur_score) {
      $path[] = $max_point;
    } else {
      break;
    }

    if (count($path) >= 10)
      break;
  }

  $output = '';
  foreach ($path as $p) {
    $output .= $points[$p][0] . ',' . $points[$p][1] . ';';
  }
  print substr($output, 0, strlen($output) - 1); //remove trailing ';'
