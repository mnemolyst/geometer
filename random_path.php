  function path_score($path) {
    global $points;

    $score = 0;
    foreach($path as $p) {
      $dist = sqrt($points[$p][0] * $points[$p][0] + $points[$p][1] * $points[$p][1]);
      $score += 1/(abs(150 - $dist));
    }
    return $score;
  }

  function point_on_line($p, $l) {
    global $points;
    global $lines;

    $d1 = array(
      $lines[$l][2] - $lines[$l][0],
      $lines[$l][3] - $lines[$l][1],
    );
    $d2 = array(
      $points[$p][0] - $lines[$l][0],
      $points[$p][1] - $lines[$l][1],
    );

    $cp = $d1[0]*$d2[1] - $d1[1]*$d2[0];

    if (abs($cp) < 0.0001) {
      return TRUE;
    } else {
      return FALSE;
    }
  }

  function valid_next_points($path) {
    global $points;

    switch (count($path)) {
      case 0:
        return array_keys($points);
        break;
      case 1:
        return $points[$path[0]]['connected'];
        break;
      default:
        $pn = $path[count($path)-1]; //p_n
        $pnm1 = $path[count($path)-2]; //p_(n-1)
        $valid_points = $points[$pn]['connected'];
        foreach ($valid_points as $p) {
          if ($p == $pnm1)
            unset ($valid_points[$p]);
        }
        return $valid_points;
        break;
    }
  }

  function rand_end($path) {
    global $points;

    $len = rand(1, 4);
    $new_path = $path;

    while (TRUE) {
      if ((count($new_path)-count($path)) >= $len) break;

      $valid_points = valid_next_points($new_path);

      if (count($valid_points) == 0) {
        break;
      } else {
        $new_path[] = $valid_points[rand(0, count($valid_points)-1)];
      }
    }

    return $new_path;
  }

